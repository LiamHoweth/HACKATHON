#!/usr/bin/env bash
# Builds the native iPad demo shell, installs it on the demo iPad, and launches it.
# The access code is read from .env.railway.local into a gitignored Swift file; it is never printed.
# Usage: scripts/build-ipad-shell.sh [device-udid]
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEVICE="${1:-00008112-0005455E36C3601E}"
SHELL_DIR="$ROOT/ipad-shell"
SECRETS="$SHELL_DIR/StillHereShell/DemoSecrets.swift"

CODE=""
if [[ -f "$ROOT/.env.railway.local" ]]; then
  CODE="$(grep -E '^RAILWAY_APP_ACCESS_TOKEN=' "$ROOT/.env.railway.local" | head -1 | cut -d= -f2- || true)"
fi
[[ -n "$CODE" ]] || echo "warning: no access code found; the app will ask for it on the setup screen" >&2
# Written via printf without echoing to the terminal; the file is gitignored.
umask 077
printf '// Generated by scripts/build-ipad-shell.sh. Gitignored. Do not commit.\nenum DemoSecrets {\n    static let accessCode = "%s"\n}\n' "$CODE" > "$SECRETS"
unset CODE

cd "$SHELL_DIR"
xcodegen generate --quiet
xcodebuild -project StillHereShell.xcodeproj -scheme StillHereShell -configuration Debug \
  -destination "id=$DEVICE" -derivedDataPath "$SHELL_DIR/build" -allowProvisioningUpdates -allowProvisioningDeviceRegistration \
  build -quiet
APP="$SHELL_DIR/build/Build/Products/Debug-iphoneos/StillHereShell.app"
xcrun devicectl device install app --device "$DEVICE" "$APP"
xcrun devicectl device process launch --device "$DEVICE" --terminate-existing com.liamhoweth.stillhere.demo
